BEGIN;


-- ============================================================
-- EXTENSIONES
-- ============================================================

CREATE EXTENSION IF NOT EXISTS vector;


-- ============================================================
-- TABLA: materia
-- ============================================================

CREATE TABLE public.materia (
    id              SERIAL PRIMARY KEY,
    codigo          VARCHAR NOT NULL UNIQUE,
    nombre          VARCHAR NOT NULL,
    anio            INTEGER NULL,
    cuatrimestre    SMALLINT NULL
);


-- ============================================================
-- TABLA: documento
-- ============================================================

CREATE TABLE public.documento (
    id              SERIAL PRIMARY KEY,
    titulo          VARCHAR NOT NULL,
    drive_id        VARCHAR NOT NULL UNIQUE,
    materia_id      INTEGER NULL,
    comision        VARCHAR NULL DEFAULT 'General',
    periodo         VARCHAR NULL,
    vigente         BOOLEAN NULL DEFAULT TRUE,
    estado          VARCHAR NULL DEFAULT 'Activo',
    indexado_en     TIMESTAMP WITHOUT TIME ZONE NULL,

    CONSTRAINT documento_materia_id_fkey
        FOREIGN KEY (materia_id)
        REFERENCES public.materia(id)
        ON DELETE SET NULL
        ON UPDATE NO ACTION
);


CREATE INDEX idx_documento_materia
    ON public.documento (materia_id);


-- ============================================================
-- TABLA: fragmento
-- ============================================================

CREATE TABLE public.fragmento (
    id              SERIAL PRIMARY KEY,
    documento_id    INTEGER NULL,
    contenido       TEXT NOT NULL,
    vector          VECTOR(768) NULL,
    orden           INTEGER NULL,

    CONSTRAINT fragmento_documento_id_fkey
        FOREIGN KEY (documento_id)
        REFERENCES public.documento(id)
        ON DELETE CASCADE
        ON UPDATE NO ACTION
);


CREATE INDEX idx_fragmento_documento
    ON public.fragmento (documento_id);


-- ============================================================
-- TABLA: sesion
-- ============================================================

CREATE TABLE public.sesion (
    id              SERIAL PRIMARY KEY,
    creado_at       TIMESTAMP WITHOUT TIME ZONE NULL
                    DEFAULT CURRENT_TIMESTAMP,
    materia_id      INTEGER NULL,
    estado          VARCHAR NULL,

    CONSTRAINT sesion_materia_id_fkey
        FOREIGN KEY (materia_id)
        REFERENCES public.materia(id)
        ON DELETE NO ACTION
        ON UPDATE NO ACTION
);


-- ============================================================
-- TABLA: consulta
-- ============================================================

CREATE TABLE public.consulta (
    id                  SERIAL PRIMARY KEY,
    sesion_id           INTEGER NULL,
    texto_sanitizado    TEXT NOT NULL,
    resultado           TEXT NULL,
    confianza           DOUBLE PRECISION NULL DEFAULT 0.0,
    creado_at           TIMESTAMP WITHOUT TIME ZONE NULL
                        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT consulta_sesion_id_fkey
        FOREIGN KEY (sesion_id)
        REFERENCES public.sesion(id)
        ON DELETE NO ACTION
        ON UPDATE NO ACTION
);


CREATE INDEX idx_consulta_creado
    ON public.consulta (creado_at);


-- ============================================================
-- TABLA: pregunta_frecuente
-- ============================================================

CREATE TABLE public.pregunta_frecuente (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pregunta_canonica   VARCHAR NOT NULL,
    embedding           VECTOR NULL,
    respuesta           VARCHAR NULL,
    materia_id          INTEGER NULL,
    comision            VARCHAR NULL,
    vigencia_hasta      DATE NULL,
    generada_en         TIMESTAMP WITHOUT TIME ZONE NULL,
    aciertos            BIGINT NULL,

    CONSTRAINT pregunta_frecuente_materia_id_fkey
        FOREIGN KEY (materia_id)
        REFERENCES public.materia(id)
        ON DELETE NO ACTION
        ON UPDATE NO ACTION
);


-- ============================================================
-- TABLA: pregunta_fuente
-- ============================================================

CREATE TABLE public.pregunta_fuente (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    drive_id    VARCHAR NULL,

    CONSTRAINT pregunta_fuente_id_fkey
        FOREIGN KEY (id)
        REFERENCES public.pregunta_frecuente(id)
        ON DELETE NO ACTION
        ON UPDATE NO ACTION,

    CONSTRAINT pregunta_fuente_drive_id_fkey
        FOREIGN KEY (drive_id)
        REFERENCES public.documento(drive_id)
        ON DELETE NO ACTION
        ON UPDATE NO ACTION
);

-- ============================================================
-- DATOS INICIALES: materias del alcance
